"""Build the viewer page from the exported model.
Usage: python3 -I build_page.py MODEL_JSON WEB_SRC_DIR OUT_HTML [--single] [--plain]

WEB_SRC_DIR holds page.html (markup), viewer.css, transcribe.js and viewer.js (joined into tpm2-model.js). Next to OUT_HTML go tpm2-model.css, tpm2-model.js and
tpm2-model-data.js: the model metadata as JSON (one part per line) and the geometry (model.bin, re-encoded, deflated,
base64 in lines of 100 characters). The page loads them with ordinary <link> and <script src>, so it also opens from
the disk (file://). With --single everything is inlined into one self-contained file. rev. 0.14: the font sets go into fonts/ beside the page.
With --plain the geometry is written readable instead: one line per shape, {"v": [x, y, z, ...], "i": [a, b, c, ...]},
vertex coordinates in steps of Q from the part's corner and triangle indices as plain integers (about 4 times larger)."""
import sys, os, json, zlib, base64
import numpy as np

src, web, out = sys.argv[1:4]
single = '--single' in sys.argv
plain = '--plain' in sys.argv
meta = json.load(open(src, encoding='utf-8'))
blob = open(os.path.splitext(src)[0] + '.bin', 'rb').read()
# rev. 0.11: font sets (tools/model/fontset.py -> gen/fonts/<id>/web.json): listed in C.FONTS; each set other than
# Alcarin goes into its own tpm2-font-<id>.js, loaded by the page when chosen (inlined with --single)
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from fontsets import FONTSETS
fdir = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(src))), 'fonts')
fonts_meta, font_files = [], {}
for f in FONTSETS:
    wj = os.path.join(fdir, f['id'], 'web.json')
    if not os.path.exists(wj):
        continue
    W = json.load(open(wj, encoding='utf-8'))
    fn = f"fonts/tpm2-font-{f['id']}.js"           # rev. 0.14: the font sets in their own folder
    fonts_meta.append(dict(id=f['id'], name=f['name'], author=f['author'], file=fn, info=W['info']))
    if f['id'] != 'alcarin':
        font_files[fn] = (W, open(os.path.join(fdir, f['id'], 'web.bin'), 'rb').read())
meta['C']['FONTS'] = fonts_meta
# rev. 0.12a: the owner's device as a texture of its plaque (drawn here from data/device/device_regions.json)
from PIL import Image, ImageDraw
import io
_root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
_D = json.load(open(os.path.join(_root, 'data', 'device', 'device_regions.json'), encoding='utf-8'))
_N, _h = 1024, _D['half_diagonal']
_img = Image.new('RGB', (_N, _N), (20, 20, 20))
_pt = lambda x, y: ((x / _h + 1) / 2 * _N, (1 - y / _h) / 2 * _N)
for _r in _D['regions']:
    for _poly in _r['polys']:
        _m = Image.new('L', (_N, _N), 0); _d = ImageDraw.Draw(_m)
        _d.polygon([_pt(*q) for q in _poly[0]], fill=255)
        for _hole in _poly[1:]:
            _d.polygon([_pt(*q) for q in _hole], fill=0)
        _img.paste(_r['color'], mask=_m)
_buf = io.BytesIO(); _img.save(_buf, 'JPEG', quality=88)
meta['C']['DEVICE_TEX'] = 'data:image/jpeg;base64,' + base64.b64encode(_buf.getvalue()).decode()


def transport(meta, blob):
    """Re-encode the shapes so that they deflate well: vertex coordinates as planar deltas (all x, all y, all z; int16),
    indices as zigzag deltas (uint16, or uint32 for the few large shapes). Each shape starts on a 4-byte boundary."""
    out, table = bytearray(), []
    for off, nv, ni, i32 in meta['geoms']:
        q = np.frombuffer(blob, np.uint16, nv * 3, off).reshape(-1, 3).T.astype(np.int32)
        io = -(-(off + nv * 6) // 4) * 4
        idx = np.frombuffer(blob, np.uint32 if i32 else np.uint16, ni, io).astype(np.int64)
        d = np.diff(idx, prepend=0)
        zz = (d << 1) ^ (d >> 63)
        wide = bool(zz.max() >= 65536)
        while len(out) % 4:
            out.append(0)
        table.append([len(out), nv, ni, wide])
        out += np.diff(q, axis=1, prepend=0).astype(np.int16).tobytes()
        while len(out) % 4:
            out.append(0)
        out += zz.astype(np.uint32 if wide else np.uint16).tobytes()
    return table, bytes(out)


meta['geoms'], packed = transport(meta, blob)
z = base64.b64encode(zlib.compress(packed, 9)).decode()

dump = lambda v: json.dumps(v, ensure_ascii=False, separators=(',', ':'))
lines = ['// ТПМ-2: data of the model viewer. Generated by tools/model/webexport.py and tools/web/build_page.py; do not edit.',
         '// meta: constants, keys, glyph outlines and one line per part (name, group, colour, motion, corner, shape index);',
         '// geom: the shapes (vertex coordinates in steps of Q from the part corner, as planar deltas; triangle indices as zigzag',
         '// deltas), deflated and base64; geoms gives [offset, vertices, indices, 32-bit indices] of each shape.',
         'window.TPM2_DATA = {', '"meta": {']
keys = list(meta)
for n, k in enumerate(keys):
    sep = ',' if n < len(keys) - 1 else ''
    if k == 'parts':
        lines.append('"parts": [')
        lines += [dump(p) + (',' if i < len(meta['parts']) - 1 else '') for i, p in enumerate(meta['parts'])]
        lines.append(']' + sep)
    else:
        lines.append(f'{dump(k)}: {dump(meta[k])}{sep}')
lines.append('},')
if plain:
    # readable geometry: one shape per line
    lines[1:4] = ['// meta: constants, keys, glyph outlines and one line per part (name, group, colour, motion, corner, shape index);',
                  '// shapes: one line per shape: "v" vertex coordinates (x, y, z of each vertex in steps of meta.Q from the part corner),',
                  '// "i" triangle vertex indices (three per triangle).']
    lines.append('"shapes": [')
    sh = []
    for off, nv, ni, i32 in json.load(open(src, encoding='utf-8'))['geoms']:
        q = np.frombuffer(blob, np.uint16, nv * 3, off)
        io = -(-(off + nv * 6) // 4) * 4
        idx = np.frombuffer(blob, np.uint32 if i32 else np.uint16, ni, io)
        sh.append(dump(dict(v=q.tolist(), i=idx.tolist())))
    lines += [x + (',' if i < len(sh) - 1 else '') for i, x in enumerate(sh)]
    lines += [']', '};', '']
else:
    lines.append('"geom": [')
    chunks = [z[i:i + 100] for i in range(0, len(z), 100)]
    lines += ['"' + c + '"' + (',' if i < len(chunks) - 1 else '') for i, c in enumerate(chunks)]
    lines += [']', '};', '']
data_js = '\n'.join(lines).replace('</', '<\\/')

font_js = {}
for fn, (W, fb) in font_files.items():
    W['geoms'], fpk = transport(W, fb)
    fz = base64.b64encode(zlib.compress(fpk, 9)).decode()
    ch = [fz[i:i + 100] for i in range(0, len(fz), 100)]
    font_js[fn] = '\n'.join(['// ТПМ-2: font set ' + W['name'] + ' of the model viewer (tools/model/fontset.py, tools/web/build_page.py); do not edit.',
                             'window.TPM2_FONTS = window.TPM2_FONTS || {};',
                             f'window.TPM2_FONTS[{dump(W["id"])}] = {{"meta": {dump(W)},', '"geom": [']
                            + ['"' + c + '"' + (',' if i < len(ch) - 1 else '') for i, c in enumerate(ch)] + [']};', '']).replace('</', '<\\/')

rd = lambda n: open(os.path.join(web, n), encoding='utf-8').read()
page, css, js = rd('page.html'), rd('viewer.css'), rd('transcribe.js') + '\n' + rd('viewer.js')
links = {'<link rel="stylesheet" href="tpm2-model.css" />': ('<style>\n' + css + '</style>', 'tpm2-model.css', css),
         '<script src="tpm2-model-data.js"></script>': ('<script>\n' + data_js + '</script>', 'tpm2-model-data.js', data_js),
         '<script src="tpm2-model.js"></script>': ('<script>\n' + js.replace('</', '<\\/') + '</script>', 'tpm2-model.js', js)}
odir = os.path.dirname(out) or '.'
for tag, (inline, fn, text) in links.items():
    assert tag in page, tag
    if single:
        page = page.replace(tag, inline)
    else:
        open(os.path.join(odir, fn), 'w', encoding='utf-8').write(text)
tag = '<script src="tpm2-model-data.js"></script>'
if single:
    page = page.replace('<script>\n' + data_js + '</script>', '<script>\n' + data_js + '</script>' + ''.join('<script>\n' + t + '</script>' for t in font_js.values()), 1)
else:
    os.makedirs(os.path.join(odir, 'fonts'), exist_ok=True)
    for fn, t in font_js.items():
        open(os.path.join(odir, fn), 'w', encoding='utf-8').write(t)
open(out, 'w', encoding='utf-8').write(page)
print(f'page {len(page) / 1e3:.0f} kB' + ('' if single else f', script {len(js) / 1e3:.0f} kB, data {len(data_js) / 1e3:.0f} kB (geometry {len(blob) / 1e3:.0f} kB raw, {len(z) / 1e3:.0f} kB packed)')
      + f'; font sets: {len(font_js)}, {sum(len(t) for t in font_js.values()) / 1e3:.0f} kB')
